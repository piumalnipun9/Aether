fn tone(hue: f64, (chroma, tone): (f64, f64)) -> String {
    let color: Argb = Hct::from(hue, chroma, tone).into();
    format!("#{:02x}{:02x}{:02x}", color.red, color.green, color.blue)
}

/// A folder in the colors of `source`, with a sheet of paper in it and maybe a symbol on it.
pub fn folder_svg(source: Argb, symbol: Option<&str>) -> String {
    let hue = Hct::new(source).get_hue();
    let (front_top, front_bottom) = (tone(hue, FRONT_TOP), tone(hue, FRONT_BOTTOM));
    let (back_top, back_bottom) = (tone(hue, BACK_TOP), tone(hue, BACK_BOTTOM));

    let symbol = symbol.map_or_else(String::new, |path| {
        let scale = SYMBOL_SIZE / 960.0;
        let x = SYMBOL_CENTER.0 - SYMBOL_SIZE / 2.0;
        let y = SYMBOL_CENTER.1 - SYMBOL_SIZE / 2.0;
        let color = tone(hue, SYMBOL);
        format!(
            "<path transform=\"translate({x} {y}) scale({scale})\" fill=\"{color}\" d=\"{path}\"/>"
        )
    });

    format!(
        r##"<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 512 512">
<defs>
<linearGradient id="front" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="{front_top}"/><stop offset="1" stop-color="{front_bottom}"/></linearGradient>
<linearGradient id="back" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="{back_top}"/><stop offset="1" stop-color="{back_bottom}"/></linearGradient>
<linearGradient id="paper" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#ffffff"/><stop offset="1" stop-color="#e6e6e6"/></linearGradient>
</defs>
<path fill="url(#back)" d="M84 72H180C194 72 206 78 216 90L236 112H428A44 44 0 0 1 472 156V396A44 44 0 0 1 428 440H84A44 44 0 0 1 40 396V116A44 44 0 0 1 84 72Z"/>
<rect x="68" y="128" width="376" height="170" rx="20" fill="url(#paper)"/>
<rect x="40" y="166" width="432" height="274" rx="40" fill="url(#front)"/>
{symbol}
</svg>
"##
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    const SOURCE: Argb = Argb {
        alpha: 255,
        red: 229,
        green: 90,
        blue: 97,
    };

    #[test]
    fn folders_follow_the_color() {
        let other = Argb {
            alpha: 255,
            red: 60,
            green: 90,
            blue: 230,
        };
        assert_ne!(folder_svg(SOURCE, None), folder_svg(other, None));
    }

    #[test]
    fn symbols_are_only_on_folders_that_have_them() {
        assert!(!folder_svg(SOURCE, None).contains("translate"));
        assert!(folder_svg(SOURCE, Some(HOME)).contains("translate"));
    }

    #[test]
    fn the_gradient_gets_darker() {
        let brightness = |(_, tone): (f64, f64)| tone;
        assert!(brightness(FRONT_BOTTOM) < brightness(FRONT_TOP));
        assert!(brightness(BACK_BOTTOM) < brightness(BACK_TOP));
    }
}
